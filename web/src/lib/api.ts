import type {
  AnySlide,
  ImageTemplate,
  MediaAsset,
  MediaSource,
  Playlist,
  Sign,
  SignPlaylist,
  SignSettings,
  SignTheme,
  SlideType,
} from '../../../shared/types';

export class ApiError extends Error {
  constructor(
    readonly status: number,
    message: string,
  ) {
    super(message);
    this.name = 'ApiError';
  }
}

/**
 * The one fetch wrapper. Exported because plugins define their own endpoints
 * (`plugins/<id>/web/client.ts`) and should get the same error handling rather
 * than each inventing it — but they do not add entries to `api` below, so
 * deleting a plugin folder leaves nothing behind.
 */
export async function apiRequest<T>(path: string, init?: RequestInit): Promise<T> {
  // A FormData body must be left to set its own Content-Type: the multipart
  // boundary is generated by the browser and lives in that header, so writing
  // it by hand produces a request the server cannot take apart.
  const multipart = init?.body instanceof FormData;

  const response = await fetch(path, {
    ...init,
    headers:
      init?.body && !multipart
        ? { 'Content-Type': 'application/json', ...init.headers }
        : init?.headers,
  });

  if (!response.ok) {
    let message = `Request failed (${response.status})`;
    try {
      const body = (await response.json()) as { error?: string };
      if (body.error) message = body.error;
    } catch {
      // Non-JSON error body; the status-based message stands.
    }
    throw new ApiError(response.status, message);
  }

  if (response.status === 204) return undefined as T;
  return (await response.json()) as T;
}

export const jsonBody = (body: unknown): RequestInit['body'] => JSON.stringify(body);

/**
 * How a sign page identifies itself to the server.
 *
 * `token` is a registered sign (`/s/<token>`). `playlistId` is the older
 * address that names a playlist outright. Neither means "whatever is on air".
 * Exactly one is ever set — see `signRefFromUrl`.
 */
export interface SignRef {
  token?: string;
  playlistId?: string;
}

function signQuery(ref: SignRef): string {
  if (ref.token) return `?token=${encodeURIComponent(ref.token)}`;
  if (ref.playlistId) return `?playlistId=${encodeURIComponent(ref.playlistId)}`;
  return '';
}

/** The event stream a sign subscribes to, carrying its token if it has one. */
export function signEventsUrl(ref: SignRef): string {
  return `/api/events${signQuery(ref)}`;
}

export const api = {
  // --- sign ---------------------------------------------------------------
  signPlaylist: (ref: SignRef, signal?: AbortSignal) =>
    apiRequest<SignPlaylist>(
      `/api/sign/playlist${signQuery(ref)}`,
      signal ? { signal } : undefined,
    ),
  // --- playlists ----------------------------------------------------------
  listPlaylists: () => apiRequest<Playlist[]>('/api/playlists'),
  createPlaylist: (name: string) =>
    apiRequest<Playlist>('/api/playlists', { method: 'POST', body: jsonBody({ name }) }),
  updatePlaylist: (id: string, patch: { name?: string; isActive?: true }) =>
    apiRequest<Playlist>(`/api/playlists/${id}`, { method: 'PATCH', body: jsonBody(patch) }),
  deletePlaylist: (id: string) => apiRequest<void>(`/api/playlists/${id}`, { method: 'DELETE' }),

  // --- signs (registered screens) -----------------------------------------
  listSigns: () => apiRequest<Sign[]>('/api/signs'),
  createSign: (input: { name: string; playlistId: string | null }) =>
    apiRequest<Sign>('/api/signs', { method: 'POST', body: jsonBody(input) }),
  updateSign: (id: string, patch: { name?: string; playlistId?: string | null }) =>
    apiRequest<Sign>(`/api/signs/${id}`, { method: 'PATCH', body: jsonBody(patch) }),
  deleteSign: (id: string) => apiRequest<void>(`/api/signs/${id}`, { method: 'DELETE' }),

  // --- slides -------------------------------------------------------------
  listSlides: (playlistId: string) =>
    apiRequest<AnySlide[]>(`/api/slides?playlistId=${encodeURIComponent(playlistId)}`),
  createSlide: (input: { playlistId: string; type: SlideType; title?: string }) =>
    apiRequest<AnySlide>('/api/slides', { method: 'POST', body: jsonBody(input) }),
  updateSlide: (
    id: string,
    patch: Partial<{
      title: string;
      /** Converts the slide, replacing its config rather than merging. */
      type: SlideType;
      theme: SignTheme;
      durationSeconds: number;
      enabled: boolean;
      startsAt: string | null;
      endsAt: string | null;
      config: unknown;
    }>,
  ) => apiRequest<AnySlide>(`/api/slides/${id}`, { method: 'PATCH', body: jsonBody(patch) }),
  deleteSlide: (id: string) => apiRequest<void>(`/api/slides/${id}`, { method: 'DELETE' }),
  duplicateSlide: (id: string) => apiRequest<AnySlide>(`/api/slides/${id}/duplicate`, { method: 'POST' }),
  reorderSlides: (playlistId: string, orderedIds: string[]) =>
    apiRequest<AnySlide[]>('/api/slides/reorder', {
      method: 'PATCH',
      body: jsonBody({ playlistId, orderedIds }),
    }),

  // --- media --------------------------------------------------------------
  listMedia: () => apiRequest<MediaAsset[]>('/api/media'),
  uploadMedia: (file: File) => {
    const form = new FormData();
    form.append('file', file);
    // No Content-Type header: the browser must set the multipart boundary.
    return apiRequest<MediaAsset>('/api/media', { method: 'POST', body: form });
  },
  deleteMedia: (id: string) => apiRequest<void>(`/api/media/${id}`, { method: 'DELETE' }),

  /**
   * Uploads bytes the panel made itself, e.g. a rasterized template.
   *
   * `source` is appended *before* the file on purpose: multipart is a stream,
   * and the server can only read fields that arrived ahead of it.
   */
  uploadImageBlob: (blob: Blob, filename: string, source?: MediaSource) => {
    const form = new FormData();
    if (source) form.append('source', JSON.stringify(source));
    form.append('file', blob, filename);
    return apiRequest<MediaAsset>('/api/media', { method: 'POST', body: form });
  },

  /** New bytes for an existing asset, so slides using it follow along. */
  replaceImageBlob: (id: string, blob: Blob, filename: string, source?: MediaSource) => {
    const form = new FormData();
    if (source) form.append('source', JSON.stringify(source));
    form.append('file', blob, filename);
    return apiRequest<MediaAsset>(`/api/media/${id}`, { method: 'PUT', body: form });
  },

  // --- image templates ----------------------------------------------------
  listTemplates: () => apiRequest<ImageTemplate[]>('/api/templates'),

  // --- settings -----------------------------------------------------------
  getSignSettings: () => apiRequest<SignSettings>('/api/settings/sign'),
  saveSignSettings: (settings: SignSettings) =>
    apiRequest<SignSettings>('/api/settings/sign', { method: 'PUT', body: jsonBody(settings) }),
};
